#!/usr/bin/env python3
"""Convert e1LibreOS C font headers into Rust-friendly data for apps/e1wm.

Outputs (into apps/e1wm/):
  font8x8.rs  — `pub static FONT8: [[u8; 8]; 128]` (LSB-first, matches the
                C renderer's `(bits >> col) & 1` convention)
  cjk.bin     — 9826 * 2 bytes of u16-LE codepoint index (ascending) followed
                by 9826 * 32 bytes of glyph bitmaps (16 rows x 2 bytes, first
                byte = left half, MSB = leftmost pixel)
"""
import os
import re
import sys

SRC = "/Users/macbook/Desktop/os/e1LibreOS/src/fbui"
DST = os.path.join(os.path.dirname(__file__), "..", "apps", "e1wm")


def parse_bytes(text):
    """All 0xNN byte literals in file order."""
    return [int(b, 16) for b in re.findall(r"0x([0-9A-Fa-f]{2})", text)]


def main():
    # ---- 8x8 ASCII font ----
    with open(os.path.join(SRC, "font8x8_basic.h")) as f:
        data = parse_bytes(f.read())
    assert len(data) == 128 * 8, f"font8x8: {len(data)} bytes"
    rows = []
    for i in range(0, len(data), 8):
        rows.append("[" + ", ".join(f"0x{b:02X}" for b in data[i:i + 8]) + "]")
    body = ",\n    ".join(rows)
    with open(os.path.join(DST, "font8x8.rs"), "w") as f:
        f.write("// generated by tools/mkfont_rs.py from e1LibreOS font8x8_basic.h (public domain)\n")
        f.write(f"pub static FONT8: [[u8; 8]; 128] = [\n    {body},\n];\n")

    # ---- 16x16 CJK font (index + bitmap) ----
    with open(os.path.join(SRC, "font16_cjk.h")) as f:
        text = f.read()
    idx_m = re.search(r"cjk_index\[CJK_COUNT\]\s*=\s*\{(.*?)\};", text, re.S)
    bmp_m = re.search(r"cjk_bitmap\[CJK_COUNT\]\[32\]\s*=\s*\{(.*?)\};", text, re.S)
    assert idx_m and bmp_m
    idx = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{4})", idx_m.group(1))]
    bmp = parse_bytes(bmp_m.group(1))
    assert len(bmp) == len(idx) * 32, f"cjk: {len(idx)} glyphs, {len(bmp)} bytes"
    blob = bytearray()
    for cp in idx:
        blob += cp.to_bytes(2, "little")
    blob += bytes(bmp)
    with open(os.path.join(DST, "cjk.bin"), "wb") as f:
        f.write(blob)
    print(f"font8x8.rs: 128 glyphs; cjk.bin: {len(idx)} glyphs, {len(blob)} bytes")


if __name__ == "__main__":
    sys.exit(main())
