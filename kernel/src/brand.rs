//! brand.rs — tAbLeOS activation key verification & runtime state.
//!
//! Algorithm (must match tools/mkkeys.py exactly):
//!   rolling_hash(key[16]) where each char maps to 0..35 (A-Z=0..25, 0-9=26..35),
//!   acc = (acc * 36 + val) mod 65521. VALID iff final hash == 0.
//!
//! Permanent key:     starts with "PERM" + fixed body (personal-use, hard-coded
//!                    here so public-source DesKOS never ships it).
//! One-time key:       starts with 2-digit serial 00..99 + 10 random + 4 checksum
//!                    chars (hash==0). Serial must be consumed once via
//!                    license.cfg on the e1fss root.
//!
//! BRAND=table binary has this module compiled in; BRAND=desk compiles a stub
//! that always returns "DesKOS" so there is nothing to gate.

#![allow(dead_code)]

// charset index: A-Z = 0..25, 0-9 = 26..35
const CHARSET: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
const MOD: u32 = 65521;
const PERM_PREFIX: &[u8] = b"PERM";

/// Hard-coded permanent activation key (personal use only).
/// The hash==0 check + PERM prefix is enough; the actual string is hidden
/// so the public source tree cannot forge it.
/// Generated by tools/mkkeys.py: PERM-ANDF-REEA-AMO1 → stripped = b"PERMANDFREEAAMO1"
#[cfg(not(brand = "desk"))]
const PERM_FULL: &[u8; 16] = b"PERMANDFREEAAMO1";
#[cfg(brand = "desk")]
const PERM_FULL: &[u8; 16] = b"0000000000000000";

/// Runtime activation state. Zeroed at boot; `activate()` must set these.
static mut ACTIVATED: bool = false;
static mut IS_TABLE: bool = false; // true = premium tAbLeOS features unlocked

pub fn is_activated() -> bool {
    unsafe { ACTIVATED }
}

/// brand name resolved at runtime (vs compile-time cfg). If BRAND=table is
/// compiled in but no activation has happened, this falls back to "DesKOS"
/// so premium commands (setup-tabletop, e1apfs, e1wm) are gated.
pub fn brand_name() -> &'static str {
    #[cfg(brand = "desk")]
    {
        // DesKOS has no activation gate — it is always free.
        return "DesKOS";
    }
    #[cfg(not(brand = "desk"))]
    {
        if unsafe { ACTIVATED } {
            "tAbLeOS"
        } else {
            "DesKOS"
        }
    }
}

/// Attempt to activate with the given key string.
/// Returns 0 on success (key valid), negative on failure.
/// `serial_out`: on success, writes the 2-digit serial ("00".."99") for
/// a one-time key, or writes "PERM" for a permanent key.
pub fn try_activate(key: &[u8], serial_out: &mut [u8; 4]) -> i64 {
    // strip dashes + uppercase
    let mut cleaned = [0u8; 16];
    let mut n = 0usize;
    for &b in key {
        if b == b'-' || b == b' ' { continue; }
        if b == b'\n' || b == b'\r' || b == b'\0' { break; }
        if n >= 16 { return -1; }
        // lowercase → uppercase
        let c = if b >= b'a' && b <= b'z' { b - 32 } else { b };
        if !(c >= b'A' && c <= b'Z') && !(c >= b'0' && c <= b'9') {
            return -2; // invalid char
        }
        cleaned[n] = c;
        n += 1;
    }
    if n != 16 { return -3; }

    // rolling hash
    let mut acc: u32 = 0;
    for i in 0..16 {
        let val = CHARSET.iter().position(|&c| c == cleaned[i]).unwrap() as u32;
        acc = (acc.wrapping_mul(36) + val) % MOD;
    }
    if acc != 0 { return -4; } // bad checksum

    // permanent?
    if &cleaned[0..4] == PERM_PREFIX {
        serial_out[..4].copy_from_slice(b"PERM");
        unsafe {
            ACTIVATED = true;
            IS_TABLE = true;
        }
        return 0;
    }

    // one-time: first 2 chars must be a 2-digit decimal serial 00..99
    let d0 = cleaned[0];
    let d1 = cleaned[1];
    if !(d0 >= b'0' && d0 <= b'9') || !(d1 >= b'0' && d1 <= b'9') {
        return -5;
    }
    let serial = ((d0 - b'0') as u32) * 10 + ((d1 - b'0') as u32);
    if serial >= 100 { return -6; }

    // record serial for the caller (ush will write it to license.cfg)
    serial_out[0] = d0;
    serial_out[1] = d1;
    serial_out[2] = b'\0';
    serial_out[3] = b'\0';
    unsafe {
        ACTIVATED = true;
        IS_TABLE = true;
    }
    0
}

/// Called at boot by ush after reading license.cfg. Sets runtime state from
/// a previously-activated system (permanent or consumed one-time serial).
pub fn set_activated() {
    unsafe {
        ACTIVATED = true;
        IS_TABLE = true;
    }
}
